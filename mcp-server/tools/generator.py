"""``generate_sysml`` —— 把 IR JSON 按固定模板渲染成 SysML v2 文本。

设计约束（技术方案 2.2 / 2.4 / 10.1）：

- **纯字符串渲染，确定性**：同一输入必然得到逐字节相同的输出（返回值里带 ``sha256``，
  测试用它证明「两次生成一致」）。
- **语法正确性由模板保证**：LLM 不接触语法；模板只产出固定的几种语句形态。
- **先校验后生成**：IR 有 error 时拒绝渲染（否则只会产出垃圾），把错误原样返回给调用方，
  让 LLM **改 JSON 而不是改文本**（方案 2.3 第 4 步）。

渲染范围（方案 9.1 的 T2）：part def / part usage、requirement def（含 doc 与属性）、
action def、state def（含 states/transitions）、attribute；relations 渲染为
``//`` 注释，风格对齐方案 2.3 的示例。

渲染策略（确定性、且不发明未经验证的语法）：

1. 每个元素渲染成 ``<signature>;``（无体）或 ``<signature> { <body> }``（有体）。
2. 子元素按 owner 关系嵌套；同一 owner 下按 ``KIND_ORDER`` 再按 id 排序。
3. ``relations`` 统一渲染为元素体内的 ``//`` 追溯注释（方案 2.3 风格）。
4. ``StateDefinition`` 的 states 渲染为 ``state <name>;``；transitions **以注释承载**，
   因为 MVP 没有可依据的官方状态机记法样本（见 ``docs/T0-调研结论.md`` 的选型结论——
   本机无可用官方解析器，不得凭空发明语法）。二期对齐老师样本模型后改为正式语句。
5. 单位与数量（``Attribute.unit`` / ``PartUsage.quantity``）同样先以行内注释承载
   （``// unit: h``、``// quantity: 8``）。数值仍是数字、单位仍是独立字段，语义不丢，
   但语法记法待二期用官方解析器回验后再改用正式语句。
"""

from __future__ import annotations

import hashlib
import json
from typing import Any, Dict, List, Optional, Tuple

from .validator import is_id, is_number, validate_model_json

#: 包级/体级的固定渲染顺序，保证确定性
KIND_ORDER: Tuple[str, ...] = (
    "PartDefinition",
    "PartUsage",
    "Requirement",
    "ActionDefinition",
    "StateDefinition",
    "Attribute",
)

#: Requirement 里按固定顺序渲染的保留字符串字段
REQUIREMENT_ORDERED_FIELDS: Tuple[str, ...] = (
    "verifyMethod",
    "priority",
    "source",
    "rationale",
)

#: Requirement 的保留字符串字段（其余按阈值渲染）
REQUIREMENT_STRING_FIELDS = frozenset(
    ("text", "acceptanceCriteria", "verifyMethod", "rationale", "source", "priority", "description")
)

HEADER = (
    "// Generated by sysml-modeling-agent - schema sysml-ir/v1.\n"
    "// Source of truth is the IR JSON; regenerate with generate_sysml. Do not edit by hand."
)


def generate_sysml(
    model: Any,
    *,
    indent: str = "    ",
    include_header: bool = True,
    validate: bool = True,
) -> Dict[str, Any]:
    """IR JSON → SysML v2 文本。

    :param model: IR JSON（dict 或 JSON 字符串）
    :param indent: 缩进单位，默认 4 个空格。
    :param include_header: 是否带两行生成器头注释（默认 True）。
    :param validate: 是否先跑 ``validate_model_json``（默认 True）。
    :return: ``{"ok", "text", "errors", "warnings", "stats", "sha256"}``
    """
    if validate:
        validation = validate_model_json(model)
        if not validation["ok"]:
            return {
                "ok": False,
                "text": "",
                "errors": validation["errors"],
                "warnings": validation["warnings"],
                "stats": {},
                "sha256": "",
                "message": "IR 未通过校验，已拒绝渲染；请修改 IR JSON 后重试（错误码见 errors）。",
            }
    else:
        validation = {"errors": [], "warnings": []}

    if isinstance(model, (str, bytes, bytearray)):
        model = json.loads(model)

    if not isinstance(model, dict):
        return {
            "ok": False,
            "text": "",
            "errors": [
                {"code": "E-ROOT-NOT-OBJECT", "element": None, "message": "IR 顶层必须是对象。"}
            ],
            "warnings": [],
            "stats": {},
            "sha256": "",
        }

    elements: List[Dict[str, Any]] = [
        e for e in (model.get("elements") or []) if isinstance(e, dict)
    ]
    package = model.get("package", "")
    renderer = _Renderer(elements, indent)

    lines: List[str] = []
    if include_header:
        lines.append(HEADER)
    lines.append("package %s {" % package)

    emitted: List[str] = []
    renderer.render_children(package, 1, lines, emitted)

    if emitted:
        lines.append("")
    lines.append("}")

    text = "\n".join(lines) + "\n"

    missing = sorted(
        e.get("id")
        for e in elements
        if is_id(e.get("id")) and e.get("id") not in emitted
    )
    if missing:
        return {
            "ok": False,
            "text": "",
            "errors": [
                {
                    "code": "E-GEN-ORPHAN",
                    "element": element_id,
                    "message": "元素 `%s` 无法被渲染：其 owner 链没有落到 package 上。" % element_id,
                }
                for element_id in missing
            ],
            "warnings": validation.get("warnings", []),
            "stats": {},
            "sha256": "",
        }

    stats = {
        "package": package,
        "elements": len(elements),
        "byKind": {kind: sum(1 for e in elements if e.get("kind") == kind) for kind in KIND_ORDER},
        "relations": sum(len(e.get("relations") or []) for e in elements),
        "lines": text.count("\n"),
        "chars": len(text),
    }

    return {
        "ok": True,
        "text": text,
        "errors": [],
        "warnings": validation.get("warnings", []),
        "stats": stats,
        "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
    }


# --------------------------------------------------------------------------------------


class _Renderer:
    """按 owner 关系把元素渲染成嵌套文本。"""

    def __init__(self, elements: List[Dict[str, Any]], indent: str) -> None:
        self.indent = indent
        self.by_id: Dict[str, Dict[str, Any]] = {}
        self.children: Dict[str, List[Dict[str, Any]]] = {}
        for element in elements:
            element_id = element.get("id")
            if not is_id(element_id):
                continue
            self.by_id[element_id] = element
            owner = element.get("owner")
            self.children.setdefault(owner if isinstance(owner, str) else "", []).append(element)

    # -- 组织 -------------------------------------------------------------------------

    def ordered_children(self, owner: str) -> List[Dict[str, Any]]:
        bucket = self.children.get(owner, [])
        ordered: List[Dict[str, Any]] = []
        for kind in KIND_ORDER:
            ordered.extend(
                sorted((e for e in bucket if e.get("kind") == kind), key=lambda e: str(e.get("id")))
            )
        ordered.extend(
            sorted(
                (e for e in bucket if e.get("kind") not in KIND_ORDER),
                key=lambda e: str(e.get("id")),
            )
        )
        return ordered

    def render_children(
        self,
        owner: str,
        depth: int,
        lines: List[str],
        emitted: List[str],
    ) -> None:
        pad = self.indent * depth
        first = True
        for kind in KIND_ORDER:
            if kind not in KIND_ORDER:
                continue
            group = sorted(
                (e for e in self.children.get(owner, []) if e.get("kind") == kind),
                key=lambda e: str(e.get("id")),
            )
            if not group:
                continue
            if depth == 1:
                lines.append("")
                lines.append(pad + "// ---- %s ----" % kind)
            first = False
            for element in group:
                self.render_element(element, depth, lines, emitted)

        extra = sorted(
            (e for e in self.children.get(owner, []) if e.get("kind") not in KIND_ORDER),
            key=lambda e: str(e.get("id")),
        )
        if extra and first:
            lines.append("")
        for element in extra:
            self.render_element(element, depth, lines, emitted)

    # -- 单个元素 ---------------------------------------------------------------------

    def render_element(
        self,
        element: Dict[str, Any],
        depth: int,
        lines: List[str],
        emitted: List[str],
    ) -> None:
        kind = element.get("kind")
        element_id = element.get("id")
        props = element.get("properties")
        props = props if isinstance(props, dict) else {}
        pad = self.indent * depth

        description = props.get("description")
        if isinstance(description, str) and description:
            lines.append(pad + "// description: %s" % _doc_text(description))

        body_children: List[str] = []
        self.render_children(str(element_id), depth + 1, body_children, emitted)
        body = self.body_lines(element, kind, props, depth + 1) + body_children
        body += self.relation_lines(element.get("relations") or [], depth + 1, str(element_id))

        signature = self.signature_of(element, kind, props)
        trailing = self.trailing_comment_of(element, kind, props)

        if body:
            lines.append(pad + signature + " {" + trailing)
            lines.extend(body)
            lines.append(pad + "}")
        else:
            lines.append(pad + signature + ";" + trailing)

        if is_id(element_id):
            emitted.append(element_id)

    def trailing_comment_of(
        self, element: Dict[str, Any], kind: str, props: Dict[str, Any]
    ) -> str:
        """语句末尾的行内注释，必须出现在 `;` 之后。

        - ``Attribute`` 的单位（``// unit: h``）
        - ``PartUsage`` 的数量（``// quantity: 8``）

        **为什么单位与数量用注释而不是语法**：两者在 SysML v2 里各有正式记法
        （单位/数量表达），但 MVP 手头没有可依据的官方样本与可运行的官方解析器
        （见 ``docs/T0-调研结论.md``），凭空写一个形态就是编造语法。因此先用注释
        如实承载，二期拿到老师的样本模型后改成正式语句并补测试。**语义不丢**：
        数值仍是数字、单位仍是独立字段，可被查询与导出。
        """
        if kind == "Attribute":
            unit = props.get("unit")
            if isinstance(unit, str) and unit:
                return "  // unit: %s" % unit
        if kind == "PartUsage":
            quantity = props.get("quantity")
            if is_number(quantity) and quantity != 1:
                return "  // quantity: %s" % _fmt_number(quantity)
        return ""

    def signature_of(self, element: Dict[str, Any], kind: str, props: Dict[str, Any]) -> str:
        name = element.get("name")
        if kind == "PartDefinition":
            prefix = "abstract " if props.get("isAbstract") is True else ""
            return "%spart def %s" % (prefix, name)
        if kind == "Requirement":
            return "requirement def %s" % name
        if kind == "ActionDefinition":
            return "action def %s" % name
        if kind == "StateDefinition":
            return "state def %s" % name
        if kind == "PartUsage":
            return "part %s : %s" % (name, self.resolve_name(props.get("typeRef")))
        if kind == "Attribute":
            value_type = props.get("valueType", "__MISSING__")
            signature = "attribute %s : %s" % (name, value_type)
            if "defaultValue" in props:
                signature += " = %s" % _fmt_literal(props["defaultValue"], value_type)
            return signature
        return "/* unknown kind %s */ %s" % (kind, name)

    def resolve_name(self, element_id: Any) -> str:
        """把 IR 的元素 id 解析成生成文本里使用的 ``name``。

        SysML v2 文本引用的是名字（``BatteryPack``），不是我们的内部 id
        （``PART-BATTERY-PACK``）；id 只出现在追溯注释里。解析不到时原样回退，
        让文本至少是可读的（validate 层已经把悬空 typeRef 拦下了）。
        """
        if isinstance(element_id, str) and element_id in self.by_id:
            name = self.by_id[element_id].get("name")
            if isinstance(name, str) and name:
                return name
        if element_id is None:
            return "__MISSING_TYPE__"
        return str(element_id)

    def body_lines(
        self,
        element: Dict[str, Any],
        kind: str,
        props: Dict[str, Any],
        depth: int,
    ) -> List[str]:
        pad = self.indent * depth
        body: List[str] = []

        if kind == "Requirement":
            text = props.get("text")
            criteria = props.get("acceptanceCriteria")
            if isinstance(text, str):
                body.append(pad + "doc /* %s */" % _doc_text(text))
            if isinstance(criteria, str):
                body.append(pad + "doc /* 验收判据: %s */" % _doc_text(criteria))
            for field in REQUIREMENT_ORDERED_FIELDS:
                if field in props and isinstance(props[field], str):
                    body.append(
                        pad
                        + "attribute %s : String = %s;"
                        % (field, json.dumps(props[field], ensure_ascii=False))
                    )
            for field in sorted(f for f in props if f not in REQUIREMENT_STRING_FIELDS):
                body.append(pad + self.threshold_line(field, props[field]))

        elif kind == "ActionDefinition":
            for field, keyword in (("inputs", "in"), ("outputs", "out")):
                for item in props.get(field) or []:
                    if not isinstance(item, dict):
                        continue
                    type_ref = item.get("typeRef")
                    statement = "%s %s%s;" % (
                        keyword,
                        item.get("name"),
                        " : %s" % type_ref if isinstance(type_ref, str) and type_ref else "",
                    )
                    unit = item.get("unit")
                    if isinstance(unit, str) and unit:
                        statement += "  // unit: %s" % unit
                    body.append(pad + statement)

        elif kind == "StateDefinition":
            initial = props.get("initial")
            if isinstance(initial, str):
                body.append(pad + "// initial state: %s" % initial)
            for state in props.get("states") or []:
                body.append(pad + "state %s;" % state)
            transitions = props.get("transitions") or []
            if transitions:
                body.append(pad + "// transitions:")
                for transition in transitions:
                    if not isinstance(transition, dict):
                        continue
                    note = ""
                    if isinstance(transition.get("trigger"), str) and transition["trigger"]:
                        note += "  [trigger: %s]" % transition["trigger"]
                    if isinstance(transition.get("guard"), str) and transition["guard"]:
                        note += "  [guard: %s]" % transition["guard"]
                    body.append(
                        pad
                        + "//   %s --> %s%s"
                        % (transition.get("from"), transition.get("to"), note)
                    )

        return body

    def relation_lines(self, relations: List[Any], depth: int, source_id: str) -> List[str]:
        if not relations:
            return []
        pad = self.indent * depth
        out = [pad + "// 追溯关系 (relations):"]
        for relation in relations:
            if not isinstance(relation, dict):
                continue
            rationale = relation.get("rationale")
            note = "  (%s)" % rationale if isinstance(rationale, str) and rationale else ""
            out.append(
                pad
                + "//   %s --%s--> %s%s"
                % (source_id, relation.get("type"), relation.get("target"), note)
            )
        return out

    def threshold_line(self, field: str, value: Any) -> str:
        if isinstance(value, bool):
            return "attribute %s : Boolean = %s;" % (field, "true" if value else "false")
        if is_number(value):
            value_type = "Integer" if isinstance(value, int) else "Real"
            return "attribute %s : %s = %s;" % (field, value_type, _fmt_number(value))
        if isinstance(value, dict):
            return "attribute %s : Real = %s;  // unit: %s" % (
                field,
                _fmt_number(value.get("value")),
                value.get("unit"),
            )
        return "// [无法渲染的阈值字段] %s = %s" % (field, _safe_json(value))


# --------------------------------------------------------------------------------------
# 格式化辅助（全部确定性）
# --------------------------------------------------------------------------------------


def _fmt_number(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value == int(value) and abs(value) < 1e16:
            return "%.1f" % value
        return repr(value)
    return str(value)


def _fmt_literal(value: Any, value_type: str) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if is_number(value):
        if value_type == "Real" and isinstance(value, int):
            return "%.1f" % float(value)
        return _fmt_number(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return _safe_json(value)


def _doc_text(value: str) -> str:
    """把任意文本收进注释，保证不会提前闭合、不跨行。"""
    text = value.replace("\r\n", " ").replace("\n", " ").replace("\r", " ")
    text = text.replace("*/", "* /")
    return " ".join(text.split())


def _safe_json(value: Any) -> str:
    try:
        return json.dumps(value, ensure_ascii=False)
    except Exception:  # noqa: BLE001
        return repr(value)


