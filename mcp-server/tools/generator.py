# 格式化辅助（全部确定性）
# --------------------------------------------------------------------------------------


def _fmt_number(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value == int(value) and abs(value) < 1e16:
            return "%.1f" % value
        return repr(value)
    return str(value)


def _fmt_literal(value: Any, value_type: str) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if is_number(value):
        if value_type == "Real" and isinstance(value, int):
            return "%.1f" % float(value)
        return _fmt_number(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return _safe_json(value)


def _doc_text(value: str) -> str:
    """把任意文本收进注释，保证不会提前闭合、不跨行。"""
    text = value.replace("\r\n", " ").replace("\n", " ").replace("\r", " ")
    text = text.replace("*/", "* /")
    return " ".join(text.split())


def _inline_text(value: str) -> str:
    """把 trigger / guard / expression 收成单行（不改变其余字符）。"""
    text = value.replace("\r\n", " ").replace("\n", " ").replace("\r", " ")
    return " ".join(text.split())


def _unit_text(value: Any) -> str:
    """单位字面量的内容：非空字符串才渲染，内部空白折叠为单个空格。

    经过 ``UNIT_ALIASES`` 映射：官方标准库没有的名字（``Wh``）渲染成等价表达式
    （``W*h``）。逆解析用同一张表的反向映射还原成 IR 的规范写法。
    """
    if isinstance(value, str) and value.strip():
        cleaned = " ".join(value.split())
        return _UNIT_ALIAS_TO_TEXT.get(cleaned, cleaned)
    return ""


def _transition_name(transition: Dict[str, Any], index: int) -> str:
    """为没有名字的 IR transition 生成确定性的 SysML 迁移名。

    官方记法 ``transition <name> first ... then ...`` 要求有名字，而 IR 的
    ``transitions[]`` 只存 from/to/trigger/guard。这里用「端点 + 数组下标」合成，
    保证同输入同名字、同一状态机内不重名；逆解析时名字本身不还原进 IR。
    """
    source = transition.get("from")
    target = transition.get("to")
    return "Transition_%s_to_%s_%d" % (source, target, index)


def _safe_json(value: Any) -> str:
    try:
        return json.dumps(value, ensure_ascii=False)
    except Exception:  # noqa: BLE001
        return repr(value)


